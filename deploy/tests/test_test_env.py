def test_compose_test_config_validates(tmp_path: Path) -> None:
    docker = shutil.which("docker")
    if docker is None:
        pytest.skip("docker CLI not available")
    if subprocess.run([docker, "compose", "version"], capture_output=True).returncode != 0:
        pytest.skip("docker compose plugin not available")
    text = COMPOSE.read_text(encoding="utf-8").replace("env/test.env]", "env/test.env.example]")
    text = text.replace("./test-secrets/", str(tmp_path) + "/")
    for name in _compose()["secrets"]:
        (tmp_path / name).write_text("x")
    check = DEPLOY / "compose" / f".compose.check.{os.getpid()}.yml"
    check.write_text(text, encoding="utf-8")
    try:
        r = subprocess.run(
            [docker, "compose", "-f", str(check), "--profile", "admin", "config", "-q"],
            capture_output=True,
            text=True,
        )
    finally:
        check.unlink()
    assert r.returncode == 0, r.stderr
