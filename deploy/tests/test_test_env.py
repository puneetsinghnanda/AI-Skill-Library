"""One-machine TEST environment with GitHub sign-in (ADR 0006, deploy/README.md).

Static checks always run; ``docker compose config`` runs when the Docker CLI and compose plugin
exist (no daemon needed).
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
from pathlib import Path
from typing import Any

import pytest
import yaml

DEPLOY = Path(__file__).resolve().parent.parent
ROOT = DEPLOY.parent
COMPOSE = DEPLOY / "compose" / "compose.test.yml"
ENV_EXAMPLE = DEPLOY / "compose" / "env" / "test.env.example"
SECRETS_SH = DEPLOY / "scripts" / "test-env-secrets.sh"
ORG_EXAMPLE = DEPLOY / "test-org.github.toml.example"


def _compose() -> dict[str, Any]:
    data: dict[str, Any] = yaml.safe_load(COMPOSE.read_text(encoding="utf-8"))
    return data


def _env() -> dict[str, str]:
    out = {}
    for line in ENV_EXAMPLE.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            k, _, v = line.partition("=")
            out[k.strip()] = v.strip()
    return out


def test_env_example_selects_github_and_test() -> None:
    env = _env()
    assert env["IDENTITY_PROVIDER"] == "github" and env["ENVIRONMENT"] == "test"
    for key in (
        "GITHUB_CLIENT_ID",
        "GITHUB_CLIENT_SECRET",
        "GITHUB_API_URL",
        "BOOTSTRAP_ADMIN_GITHUB_LOGINS",
        "PUBLIC_BASE_URL",
    ):
        assert key in env, key
    assert env["GITHUB_CLIENT_SECRET"].startswith("REPLACE-"), "placeholder only"
    assert env["SERVE_PORTAL"] == "true"


def test_settings_accept_the_env_example(monkeypatch: pytest.MonkeyPatch) -> None:
    import sys

    sys.path.insert(0, str(ROOT / "services" / "insights"))
    try:
        from app.config import Settings
    finally:
        sys.path.pop(0)
    for k, v in _env().items():
        monkeypatch.setenv(k, v)
    s = Settings()
    assert s.identity_provider == "github" and s.env == "test"
    assert s.bootstrap_admin_github_logins == ("your-github-login",)
    s.check_identity()  # github + test is allowed
    monkeypatch.setenv("ENVIRONMENT", "prod")
    with pytest.raises(RuntimeError):
        Settings().check_identity()


def test_only_api_publishes_a_port_and_db_is_internal() -> None:
    c = _compose()
    published = {n for n, svc in c["services"].items() if svc.get("ports")}
    assert published == {"api"}
    assert c["networks"]["db"] == {"internal": True}
    assert c["services"]["postgres"]["networks"] == ["db"]
    for name in ("api", "worker", "migrate", "admin"):
        svc = c["services"][name]
        assert svc["read_only"] is True and svc["user"] == "10001", name
        assert "no-new-privileges:true" in svc["security_opt"], name
        assert svc["env_file"] == ["env/test.env"], name


def test_secrets_come_from_git_ignored_files() -> None:
    c = _compose()
    script = SECRETS_SH.read_text(encoding="utf-8")
    for name, spec in c["secrets"].items():
        assert spec["file"].startswith("./test-secrets/"), name
        assert f"gen {name} " in script, f"{name} not generated by test-env-secrets.sh"
    ignore = (DEPLOY / ".gitignore").read_text(encoding="utf-8")
    assert "compose/test-secrets/" in ignore and "test-org.github.toml" in ignore
    assert re.search(r"^\*\.env$", ignore, re.M), "env/test.env must be ignored"
    assert os.access(SECRETS_SH, os.X_OK)
    bash = shutil.which("bash")
    if bash:
        subprocess.run([bash, "-n", str(SECRETS_SH)], check=True)


def test_image_builds_portal_in_github_mode() -> None:
    df = (DEPLOY / "images" / "test-env" / "Dockerfile").read_text(encoding="utf-8")
    assert "VITE_IDENTITY_PROVIDER=github" in df and "VITE_ENVIRONMENT=test" in df
    assert "SERVE_PORTAL=true" in df and "COPY --from=portal /app/dist /app/portal" in df
    ignore = (DEPLOY / "images" / "test-env" / "Dockerfile.dockerignore").read_text()
    assert "**/node_modules" in ignore and "deploy/compose/test-secrets" in ignore


def test_org_example_is_github() -> None:
    import tomllib

    data = tomllib.loads(ORG_EXAMPLE.read_text(encoding="utf-8"))
    assert data["provider"] == "github" and data["configured"] is True
    assert data["github_oauth_url"] == "https://github.com"


def test_edge_routes_github_sign_in_to_the_api() -> None:
    conf = (DEPLOY / "compose" / "edge" / "nginx.conf").read_text(encoding="utf-8")
    block = conf[conf.index("location ^~ /auth/github/") :]
    assert block.index("proxy_pass http://$api;") < block.index("location / {")
    assert "location = /auth/logout" in conf


