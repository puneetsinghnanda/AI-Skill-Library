// Generates src/api/schema.d.ts from the committed insights OpenAPI (SDD-09 §3.2, §13).
//
// The OpenAPI holds one external $ref (the ingest event envelope on POST /v1/events, served by an
// internal schema host). The portal never calls that route, and CI must not reach the network, so
// external refs are replaced by an open schema before generation. Everything else is used as is.
//
//   node scripts/gen-api.mjs            write src/api/schema.d.ts
//   node scripts/gen-api.mjs --stdout   print the generated text (used by check-schema-drift.mjs)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import * as prettier from 'prettier';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const specPath = resolve(root, '../services/insights/openapi/openapi.json');
const outPath = resolve(root, 'src/api/schema.d.ts');

function localOnly(node) {
  if (Array.isArray(node)) return node.map(localOnly);
  if (node && typeof node === 'object') {
    if (typeof node.$ref === 'string' && !node.$ref.startsWith('#')) {
      return { description: `External schema ${node.$ref} (not used by the portal)` };
    }
    return Object.fromEntries(Object.entries(node).map(([k, v]) => [k, localOnly(v)]));
  }
  return node;
}

export async function generate() {
  const spec = localOnly(JSON.parse(readFileSync(specPath, 'utf8')));
  const ast = await openapiTS(spec, { alphabetize: true });
  const banner =
    '/**\n * Generated by scripts/gen-api.mjs from services/insights/openapi/openapi.json.\n' +
    ' * Do not edit by hand. CI fails when this file drifts from the OpenAPI (npm run check:api).\n */\n\n';
  const text = banner + astToString(ast);
  const cfg = (await prettier.resolveConfig(outPath)) ?? {};
  return prettier.format(text, { ...cfg, parser: 'typescript' });
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = await generate();
  if (process.argv.includes('--stdout')) process.stdout.write(out);
  else {
    writeFileSync(outPath, out);
    console.log(`wrote ${outPath}`);
  }
}
